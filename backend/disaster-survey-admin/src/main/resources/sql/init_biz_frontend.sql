-- ---------- 1. 灾害事件主表（新增） ----------
CREATE TABLE T_BIZ_DISASTER_EVENT (
	ID VARCHAR(64) NOT NULL,
	EVENT_CODE VARCHAR(128),
	EVENT_NAME VARCHAR(256),
	DISASTER_TYPES VARCHAR(256),
	REGION_CODE VARCHAR(64),
	REGION_NAME VARCHAR(128),
	OCCUR_TIME TIMESTAMP,
	STATUS VARCHAR(32),
	CJR VARCHAR(64),
	CJSJ TIMESTAMP,
	ZHGXR VARCHAR(64),
	ZHGXSJ TIMESTAMP,
	CONSTRAINT PK_T_BIZ_DISASTER_EVENT PRIMARY KEY (ID)
);

CREATE INDEX IDX_BIZ_EVENT_CODE ON T_BIZ_DISASTER_EVENT(EVENT_CODE);
CREATE INDEX IDX_BIZ_EVENT_STATUS ON T_BIZ_DISASTER_EVENT(STATUS);
CREATE INDEX IDX_BIZ_EVENT_REGION ON T_BIZ_DISASTER_EVENT(REGION_CODE);

-- ---------- 2. 灾情调查基线表（含 event_id 主线结构化字段） ----------
CREATE TABLE T_BIZ_SURVEY_BASELINE (
	ID VARCHAR(64) NOT NULL,
	EVENT_ID VARCHAR(64),
	VERSION_NO INT,
	STATUS VARCHAR(32),
	RS_IMAGE_ID VARCHAR(128),
	AFFECTED_AREA_GEOJSON CLOB,
	AFFECTED_POPULATION DECIMAL(18,2),
	TOWN_AREA_STATS_JSON CLOB,
	EXPOSURE_OVERLAY_JSON CLOB,
	COMPARE_CHECK_JSON CLOB,
	CONFIRMED_TIME TIMESTAMP,
	CONFIRMED_BY VARCHAR(64),
	SCENE_ID VARCHAR(128),
	DISTRICT VARCHAR(128),
	JSON_DATA CLOB,
	REMARK VARCHAR(512),
	CJR VARCHAR(64),
	CJSJ TIMESTAMP,
	ZHGXR VARCHAR(64),
	ZHGXSJ TIMESTAMP,
	CONSTRAINT PK_T_BIZ_SURVEY_BASELINE PRIMARY KEY (ID)
);

CREATE INDEX IDX_BIZ_BASELINE_SCENE ON T_BIZ_SURVEY_BASELINE(SCENE_ID);
CREATE INDEX IDX_BIZ_BASELINE_EVENT ON T_BIZ_SURVEY_BASELINE(EVENT_ID);
CREATE INDEX IDX_BIZ_BASELINE_STATUS ON T_BIZ_SURVEY_BASELINE(STATUS);

-- ---------- 3. 承灾体现场核查档案表 ----------
CREATE TABLE T_BIZ_HAZARD_DOSSIER (
	ID VARCHAR(64) NOT NULL,
	EVENT_ID VARCHAR(64),
	BASELINE_ID VARCHAR(64),
	EXPOSURE_TYPE VARCHAR(64),
	EXPOSURE_ID VARCHAR(128),
	RS_CLIP_IMAGE_URL VARCHAR(1024),
	FIELD_ATTACHMENTS_JSON CLOB,
	BIZ_KEY VARCHAR(256) NOT NULL,
	HAZARD_TYPE VARCHAR(64),
	HAZARD_NAME VARCHAR(256),
	VERIFY_STATUS VARCHAR(64),
	ARCHIVE_STATUS VARCHAR(64),
	ARCHIVE_NO VARCHAR(128),
	JSON_DATA CLOB,
	REMARK VARCHAR(512),
	CJR VARCHAR(64),
	CJSJ TIMESTAMP,
	ZHGXR VARCHAR(64),
	ZHGXSJ TIMESTAMP,
	CONSTRAINT PK_T_BIZ_HAZARD_DOSSIER PRIMARY KEY (ID)
);

CREATE INDEX IDX_BIZ_DOSSIER_KEY ON T_BIZ_HAZARD_DOSSIER(BIZ_KEY);
CREATE INDEX IDX_BIZ_DOSSIER_ARCH ON T_BIZ_HAZARD_DOSSIER(ARCHIVE_STATUS);
CREATE INDEX IDX_BIZ_DOSSIER_EVENT ON T_BIZ_HAZARD_DOSSIER(EVENT_ID);
CREATE INDEX IDX_BIZ_DOSSIER_EXPOSURE ON T_BIZ_HAZARD_DOSSIER(EXPOSURE_TYPE);

-- ---------- 4. 灾害评估记录表（新增，取代万能表评估存储） ----------
CREATE TABLE T_BIZ_ASSESSMENT_RECORD (
	ID VARCHAR(64) NOT NULL,
	EVENT_ID VARCHAR(64) NOT NULL,
	BASELINE_ID VARCHAR(64),
	DISASTER_TYPE VARCHAR(64) NOT NULL,
	SUB_TYPE VARCHAR(64) NOT NULL,
	REGION_CODE VARCHAR(64),
	INPUT_PARAMS_JSON CLOB,
	RESULT_DATA_JSON CLOB,
	COMPUTE_MODE VARCHAR(32),
	STATUS VARCHAR(32),
	CJR VARCHAR(64),
	CJSJ TIMESTAMP,
	ZHGXR VARCHAR(64),
	ZHGXSJ TIMESTAMP,
	CONSTRAINT PK_T_BIZ_ASSESSMENT_RECORD PRIMARY KEY (ID)
);

CREATE INDEX IDX_BIZ_ASSESS_EVENT ON T_BIZ_ASSESSMENT_RECORD(EVENT_ID);
CREATE INDEX IDX_BIZ_ASSESS_TYPE ON T_BIZ_ASSESSMENT_RECORD(DISASTER_TYPE, SUB_TYPE);
CREATE INDEX IDX_BIZ_ASSESS_STATUS ON T_BIZ_ASSESSMENT_RECORD(STATUS);

-- ---------- 5. 评估报告归档表 ----------
CREATE TABLE T_BIZ_REPORT_ARCHIVE (
	ID VARCHAR(64) NOT NULL,
	EVENT_ID VARCHAR(64),
	ASSESSMENT_ID VARCHAR(64),
	DISASTER_TYPE VARCHAR(64),
	REPORT_FILE_PATH VARCHAR(1024),
	REPORT_FORMAT VARCHAR(32),
	SUMMARY_JSON CLOB,
	REPORT_NO VARCHAR(128),
	TITLE VARCHAR(512),
	TYPE_ID VARCHAR(64),
	TYPE_LABEL VARCHAR(64),
	DISTRICT VARCHAR(128),
	SCENE_NAME VARCHAR(256),
	GRADE VARCHAR(64),
	TOTAL_SCORE DECIMAL(12,2),
	ARCHIVED_AT VARCHAR(64),
	ARCHIVED_BY VARCHAR(128),
	REMARK VARCHAR(512),
	SNAPSHOT CLOB,
	CJR VARCHAR(64),
	CJSJ TIMESTAMP,
	ZHGXR VARCHAR(64),
	ZHGXSJ TIMESTAMP,
	CONSTRAINT PK_T_BIZ_REPORT_ARCHIVE PRIMARY KEY (ID)
);

CREATE INDEX IDX_BIZ_RPT_NO ON T_BIZ_REPORT_ARCHIVE(REPORT_NO);
CREATE INDEX IDX_BIZ_RPT_EVENT ON T_BIZ_REPORT_ARCHIVE(EVENT_ID);
CREATE INDEX IDX_BIZ_RPT_DISASTER ON T_BIZ_REPORT_ARCHIVE(DISASTER_TYPE);

-- ---------- 6. 前端万能表（兼容保留，阶段五后废弃写入） ----------
CREATE TABLE T_BIZ_FRONTEND_DATA (
	ID VARCHAR(64) NOT NULL,
	DATA_TYPE VARCHAR(64) NOT NULL,
	BIZ_KEY VARCHAR(128),
	NAME VARCHAR(256),
	EXTRA_TYPE VARCHAR(64),
	JSON_DATA CLOB,
	SORT_INDEX INT,
	REMARK VARCHAR(512),
	CJR VARCHAR(64),
	CJSJ TIMESTAMP,
	ZHGXR VARCHAR(64),
	ZHGXSJ TIMESTAMP,
	CONSTRAINT PK_T_BIZ_FRONTEND_DATA PRIMARY KEY (ID)
);

CREATE INDEX IDX_BIZ_FE_TYPE ON T_BIZ_FRONTEND_DATA(DATA_TYPE);
CREATE INDEX IDX_BIZ_FE_BIZKEY ON T_BIZ_FRONTEND_DATA(BIZ_KEY);

